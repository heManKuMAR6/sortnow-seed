/**
 * Compiles packs/<id>/pack.json and its SVG files into packages/packs/index.ts.
 * Sanitizes every asset, enforces size budgets, and hashes the result.
 * `--check` fails if the committed output is stale, so artwork never changes without a reviewed rebuild.
 */
import {readFile, readdir, writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {gzipSync} from 'node:zlib';
import {sanitizeSvg} from './svg-sanitize.mjs';
import {pathToFileURL} from 'node:url';

const OUT = 'packages/packs/index.ts';
const ASSET_BYTES = 12 * 1024, PACK_GZIP_BYTES = 30 * 1024;
const KINDS = ['illustrations', 'icons', 'decorations', 'particles'];
const ID = /^[a-z][a-z0-9-]{0,31}$/, HEX = /^#[0-9a-f]{6}$/i, TEXT = /^[^\u0000-\u001f\u007f<>&]{1,240}$/;
const fail = (where, message) => { throw new Error(`${where}: ${message}`); };
const keys = (o, allowed, where) => { for (const k of Object.keys(o)) if (!allowed.includes(k)) fail(where, `unknown field ${k}`); };

export async function compilePack(dir) {
  const where = `${dir}/pack.json`;
  const m = JSON.parse(await readFile(where, 'utf8'));
  keys(m, ['packVersion', 'id', 'version', 'name', 'occasions', 'license', 'signatureColors', ...KINDS, 'copy', 'effects'], where);
  if (m.packVersion !== 1) fail(where, 'packVersion must be 1');
  if (!ID.test(m.id)) fail(where, 'invalid id');
  if (!/^\d{1,4}\.\d{1,4}\.\d{1,4}$/.test(m.version)) fail(where, 'version must be semver like 1.0.0');
  if (!TEXT.test(m.name) || !Array.isArray(m.occasions) || !m.occasions.every(o => ID.test(o))) fail(where, 'invalid name or occasions');
  if (!['CC0-1.0', 'MIT'].includes(m.license)) fail(where, 'license must be CC0-1.0 or MIT');
  const signatureColors = {};
  for (const [name, hex] of Object.entries(m.signatureColors ?? {})) { if (!ID.test(name) || !HEX.test(hex)) fail(where, `invalid signature colour ${name}`); signatureColors[name] = hex.toLowerCase(); }
  const pack = {packVersion: 1, id: m.id, version: m.version, hash: '', name: m.name, occasions: [...m.occasions], license: m.license, signatureColors};
  for (const kind of KINDS) {
    pack[kind] = {};
    for (const [id, a] of Object.entries(m[kind] ?? {})) {
      const at = `${where} ${kind}.${id}`;
      if (!ID.test(id)) fail(at, 'invalid asset id');
      keys(a, ['file', 'label', 'source'], at);
      if (!a.source || !TEXT.test(a.source)) fail(at, 'record the artwork source');
      if (a.label !== undefined && !TEXT.test(a.label)) fail(at, 'invalid label');
      const raw = await readFile(`${dir}/${a.file}`, 'utf8');
      if (Buffer.byteLength(raw) > ASSET_BYTES) fail(at, `exceeds ${ASSET_BYTES} bytes`);
      const {svg, aspect} = sanitizeSvg(raw, {where: at, prefix: `seed-${m.id}-${id}`, signatureColors: Object.keys(signatureColors)});
      pack[kind][id] = {svg, aspect, ...(a.label ? {label: a.label} : {})};
    }
  }
  const copy = m.copy ?? {};
  keys(copy, ['hero', 'banner'], `${where} copy`);
  pack.copy = {hero: [...(copy.hero ?? [])], banner: [...(copy.banner ?? [])]};
  if (![...pack.copy.hero, ...pack.copy.banner].every(t => TEXT.test(t))) fail(where, 'copy must be plain text');
  pack.effects = {};
  for (const [effect, spec] of Object.entries(m.effects ?? {})) {
    const kind = effect === 'flyby' ? 'illustrations' : effect === 'particles' ? 'particles' : fail(where, `unknown effect ${effect}`);
    if (!spec.assets.every(id => Object.hasOwn(pack[kind], id))) fail(where, `effect ${effect} names a missing ${kind} asset`);
    pack.effects[effect] = {assets: [...spec.assets]};
  }
  const body = JSON.stringify({...pack, hash: undefined});
  if (gzipSync(body).length > PACK_GZIP_BYTES) fail(where, `pack exceeds ${PACK_GZIP_BYTES} bytes gzipped`);
  pack.hash = `sha256-${createHash('sha256').update(body).digest('hex')}`;
  return pack;
}

export async function buildPacks() {
  const dirs = (await readdir('packs', {withFileTypes: true})).filter(d => d.isDirectory()).map(d => d.name).sort();
  const packs = [];
  for (const d of dirs) packs.push(await compilePack(`packs/${d}`));
  const name = id => id.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
  return [
    '// Generated by scripts/build-packs.mjs from packs/*. Do not edit; edit the pack sources and rebuild.',
    "import type {CompiledPack} from '../core/pack.js';",
    ...packs.map(p => `export const ${name(p.id)}: CompiledPack = ${JSON.stringify(p, null, 2)};`),
    `export const packs: readonly CompiledPack[] = Object.freeze([${packs.map(p => name(p.id)).join(', ')}]);`,
    '',
  ].join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const out = await buildPacks();
  if (process.argv.includes('--check')) {
    const current = await readFile(OUT, 'utf8').catch(() => '');
    if (current !== out) { console.error(`${OUT} is stale: run node scripts/build-packs.mjs`); process.exit(1); }
  } else await writeFile(OUT, out);
}
