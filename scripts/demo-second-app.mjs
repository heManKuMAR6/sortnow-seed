import {build} from 'esbuild';
import {createServer} from 'node:http';
import {readFile,mkdir} from 'node:fs/promises';
import {createElement} from 'react';
import {renderToString} from 'react-dom/server';
import {Demo} from '../examples/second-app/app.mjs';
const dir='examples/second-app';
const json=async name=>JSON.parse(await readFile(`${dir}/${name}.json`,'utf8'));
const port=Number(process.env.PORT)||4174;
await mkdir('.demo',{recursive:true});
await build({entryPoints:[`${dir}/client.mjs`],bundle:true,format:'esm',outfile:'.demo/second-app.js'});
const config={brand:await json('brand'),experiences:await json('experiences'),approvals:await json('reviewed-approvals')};
const page=(await readFile(`${dir}/index.html`,'utf8')).replace('<!--ssr-->',()=>renderToString(createElement(Demo,config)));
const headers={'X-Content-Type-Options':'nosniff','Content-Security-Policy':"default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline'; connect-src 'none'; object-src 'none'; base-uri 'none'; frame-ancestors 'none'"};
const routes={'/':[async()=>page,'text/html'],'/client.js':[()=>readFile('.demo/second-app.js'),'text/javascript'],'/style.css':[()=>readFile(`${dir}/style.css`),'text/css']};
createServer(async(req,res)=>{const route=routes[req.url];if(!route){res.writeHead(404);res.end('Not found');return;}try{const body=await route[0]();res.writeHead(200,{...headers,'Content-Type':route[1]});res.end(body);}catch{res.writeHead(500);res.end('Unable to serve demo');}}).listen(port,'127.0.0.1',()=>console.log('SEED second app: http://127.0.0.1:'+port));
